import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import prettier from "prettier";

const webRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const option = (name) =>
  process.argv
    .find((arg) => arg.startsWith(`--${name}=`))
    ?.slice(name.length + 3);
const schemaUrl = option("schema")
  ? pathToFileURL(path.resolve(option("schema")))
  : new URL("../../../contracts/openapi.json", import.meta.url);
const outputDir = option("output-dir")
  ? path.resolve(option("output-dir"))
  : path.join(webRoot, "src/api/generated");
const types = astToString(await openapiTS(schemaUrl));
const client = `// Generated by scripts/contracts.mjs. Do not edit.
import createClient from "openapi-fetch";
import type { paths } from "./schema";

export function createApiClient(baseUrl = "", fetcher: typeof fetch = fetch) {
  return createClient<paths>({ baseUrl, fetch: fetcher });
}
`;
const outputs = new Map([
  ["schema.ts", await prettier.format(types, { parser: "typescript" })],
  ["client.ts", await prettier.format(client, { parser: "typescript" })],
]);
for (const [name, content] of outputs) {
  const target = path.join(outputDir, name);
  if (process.argv.includes("--check")) {
    const current = await fs.readFile(target, "utf8").catch(() => null);
    if (current !== content)
      throw new Error(`Generated client drift: ${name}; run make contracts`);
  } else {
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content);
  }
}
